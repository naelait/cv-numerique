import cors from 'cors';
import express from 'express';
import { buildPersonaSystemPrompt } from '../src/app/persona.context.ts';
import { buildKnowledgeChunks } from './knowledge.ts';
import { formatRetrievedContext, retrieveChunks } from './retrieve.ts';

const PORT = Number(process.env.PORT ?? 3001);
const OLLAMA_URL = process.env.OLLAMA_URL ?? 'http://127.0.0.1:11434';
const OLLAMA_MODEL = process.env.OLLAMA_MODEL ?? 'qwen2.5:14b';

const app = express();
app.use(cors({ origin: true }));
app.use(express.json({ limit: '32kb' }));

const systemPrompt = buildPersonaSystemPrompt();
const knowledgeCorpus = buildKnowledgeChunks();

interface ChatMessage {
  role: 'user' | 'assistant';
  content: string;
}

async function ollamaReachable(): Promise<boolean> {
  try {
    const res = await fetch(`${OLLAMA_URL}/api/tags`, { signal: AbortSignal.timeout(3000) });
    return res.ok;
  } catch {
    return false;
  }
}

async function modelAvailable(): Promise<boolean> {
  try {
    const res = await fetch(`${OLLAMA_URL}/api/tags`, { signal: AbortSignal.timeout(3000) });
    if (!res.ok) return false;
    const data = (await res.json()) as { models?: { name: string }[] };
    const baseModel = OLLAMA_MODEL.split(':')[0];
    return (
      data.models?.some(
        (m) => m.name === OLLAMA_MODEL || m.name.startsWith(`${baseModel}:`),
      ) ?? false
    );
  } catch {
    return false;
  }
}

app.get('/api/health', async (_req, res) => {
  const ollama = await ollamaReachable();
  const model = ollama ? await modelAvailable() : false;
  res.json({
    ok: ollama && model,
    ollama,
    model,
    modelName: OLLAMA_MODEL,
    mode: 'full-llm+rag',
    chunks: knowledgeCorpus.length,
  });
});

app.post('/api/chat', async (req, res) => {
  const messages = req.body?.messages as ChatMessage[] | undefined;

  if (!Array.isArray(messages) || messages.length === 0) {
    res.status(400).json({ error: 'messages requis' });
    return;
  }

  const last = messages.at(-1);
  if (!last || last.role !== 'user' || typeof last.content !== 'string' || !last.content.trim()) {
    res.status(400).json({ error: 'dernier message utilisateur invalide' });
    return;
  }

  if (!(await ollamaReachable())) {
    res.status(503).json({
      error: 'Persona indisponible pour le moment.',
    });
    return;
  }

  if (!(await modelAvailable())) {
    res.status(503).json({
      error: 'Persona indisponible pour le moment.',
    });
    return;
  }

  try {
    const recent = messages.slice(-16);
    const retrieved = retrieveChunks(last.content, knowledgeCorpus, 5);
    const contextBlock = formatRetrievedContext(retrieved);

    // Every answer is generated by the LLM — retrieval only selects which CV facts to show it
    const ollamaRes = await fetch(`${OLLAMA_URL}/v1/chat/completions`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        model: OLLAMA_MODEL,
        messages: [
          { role: 'system', content: systemPrompt },
          {
            role: 'system',
            content: `Contexte CV pertinent pour cette question (source de vérité):\n${contextBlock}`,
          },
          {
            role: 'system',
            content:
              'Lis l’historique ci-dessous. Continue la conversation sans te répéter ni reposer une question déjà traitée. Si le user a déjà demandé “et toi ?”, réponds sur toi sans renvoyer la question.',
          },
          ...recent,
        ],
        temperature: 0.35,
        top_p: 0.9,
        frequency_penalty: 0.55,
        presence_penalty: 0.25,
        max_tokens: 180,
        stream: false,
      }),
      signal: AbortSignal.timeout(120_000),
    });

    if (!ollamaRes.ok) {
      const detail = await ollamaRes.text();
      res.status(502).json({ error: `Ollama error: ${detail.slice(0, 200)}` });
      return;
    }

    const data = (await ollamaRes.json()) as {
      choices?: { message?: { content?: string } }[];
    };
    const reply = data.choices?.[0]?.message?.content?.trim();

    if (!reply) {
      res.status(502).json({ error: 'Réponse vide du modèle' });
      return;
    }

    res.json({ reply });
  } catch {
    res.status(504).json({ error: 'Timeout — le modèle met trop de temps à répondre.' });
  }
});

const server = app.listen(PORT, () => {
  console.log(`Persona chat → http://localhost:${PORT} (full LLM + RAG)`);
  console.log(`Ollama       → ${OLLAMA_URL} (${OLLAMA_MODEL})`);
  console.log(`Knowledge    → ${knowledgeCorpus.length} chunks`);
});

server.on('error', (err: NodeJS.ErrnoException) => {
  if (err.code === 'EADDRINUSE') {
    console.error(`Port ${PORT} encore pris. Relance npm run chat.`);
    process.exit(1);
  }
  throw err;
});
